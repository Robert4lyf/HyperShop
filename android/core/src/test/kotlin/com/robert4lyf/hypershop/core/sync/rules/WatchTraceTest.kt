package com.robert4lyf.hypershop.core.sync.rules

import org.junit.jupiter.api.Assertions.assertEquals
import org.junit.jupiter.api.Test
import java.io.File

/**
 * Writes garmin/test/SyncTraces.mc from the sync vectors: for each one, every
 * call [SyncHarness] made into [WatchSyncModel] and the state after it. The
 * Monkey C port (WatchSync.mc) replays them in garmin/test/TraceTest.mc, so the
 * two watch implementations are held to the same behaviour step by step.
 *
 * Fails when the checked-in file is stale. To regenerate:
 * `UPDATE_WATCH_TRACES=1 tools/gradle.sh :core:test --tests "*WatchTraceTest*"`.
 */
class WatchTraceTest {
    private val out = File("../../garmin/test/SyncTraces.mc")

    @Test
    fun tracesAreCurrent() {
        val files = SyncHarness.dir.listFiles { f -> f.extension == "json" }.orEmpty().sortedBy { it.name }
        val text =
            buildString {
                append(HEADER)
                for (f in files) {
                    val harness = SyncHarness.load(f)
                    harness.run()
                    val name = f.nameWithoutExtension.split('-').joinToString("") { it.replaceFirstChar(Char::uppercase) }
                    append("\n(:test)\n")
                    append("function trace$name(logger as Test.Logger) as Lang.Boolean {\n")
                    append("    return TraceReplay.run(logger, \"${f.nameWithoutExtension}\", [\n")
                    for (event in harness.trace) append("        ").append(literal(event)).append(",\n")
                    append("    ]);\n}\n")
                }
            }
        if (System.getenv("UPDATE_WATCH_TRACES") == "1") out.writeText(text)
        assertEquals(text, out.takeIf { it.exists() }?.readText(), "garmin/test/SyncTraces.mc is stale; see the KDoc to regenerate")
    }

    private fun literal(v: Any?): String =
        when (v) {
            null -> "null"
            is Boolean, is Int -> v.toString()
            is Long -> if (v in Int.MIN_VALUE..Int.MAX_VALUE) v.toString() else error("long $v")
            is String -> "\"" + v.replace("\\", "\\\\").replace("\"", "\\\"") + "\""
            is List<*> -> v.joinToString(", ", "[", "]") { literal(it) }
            is Map<*, *> -> if (v.isEmpty()) "{}" else v.entries.joinToString(", ", "{", "}") { entry(it) }
            else -> error("no Monkey C literal for ${v::class}")
        }

    private fun entry(e: Map.Entry<*, *>) = "${literal(e.key)} => ${literal(e.value)}"

    private companion object {
        const val HEADER = """// Generated by android/core/.../sync/rules/WatchTraceTest.kt from
// testdata/sync/*.json. Do not edit: regenerate with
//   UPDATE_WATCH_TRACES=1 tools/gradle.sh :core:test --tests "*WatchTraceTest*"
//
// Each trace is every call the Kotlin watch model received while the vector
// ran, each followed by the state it was left in:
//   ["state", view, outboxSeqs, ackedThrough, nextSeq, epoch, listRev,
//    helloDue, noticeCode, noticeCount, results]

using Toybox.Lang;
using Toybox.Test;
"""
    }
}
